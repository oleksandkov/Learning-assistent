#include <iostream>   // ввід/вивід у консоль (cerr, cout)
#include <fstream>    // робота з файлами (ifstream/ofstream)
#include <vector>     // динамічний масив std::vector
#include <algorithm>  // std::sort для сортування ребер
#include <random>     // генератор випадкових чисел для створення графів
#include <set>        // перевірка унікальності ребер при генерації
#include <cstdlib>    // std::atoi для розбору аргументів командного рядка

using namespace std;

// ============================================================
// Лабораторна робота №7 — варіант 12.
//
// ЗАДАЧА
//   Дано неорієнтований зважений зв'язковий граф. Потрібно знайти
//   вагу його мінімального кістяка (MST — Minimum Spanning Tree):
//   підмножини ребер, що з'єднує всі вершини без циклів і має
//   найменшу можливу суму ваг.
//
// АЛГОРИТМ — Краскала (Kruskal)
//   1. Зчитати всі ребра.
//   2. Відсортувати ребра за вагою у порядку зростання.
//   3. Ініціалізувати DSU: кожна вершина — окрема компонента.
//   4. Послідовно брати найлегше ребро:
//        - якщо його кінці у різних компонентах -> додати до кістяка
//          (об'єднати компоненти, додати вагу до відповіді);
//        - інакше -> пропустити (ребро утворює цикл).
//   5. Зупинитися, коли додано N-1 ребер (кістяк побудовано).
//
// СКЛАДНІСТЬ
//   Сортування: O(M log M). Операції DSU зі стисненням шляху та
//   об'єднанням за рангом: майже O(α(N)) на операцію (α — обернена
//   функція Аккермана, практично константа). Загалом: O(M log M).
//
// ВХІД/ВИХІД
//   Вхід:  input.txt  (N M, потім M рядків "A B C")
//   Вихід: output.txt (одне число — вага мінімального кістяка)
// ============================================================

// ---------- Ребро графа ----------
// Зберігає дві вершини, які з'єднує ребро, та його вагу.
// Використовується як елемент масиву ребер для сортування.
struct Edge {
    int u;  // номер першої вершини
    int v;  // номер другої вершини
    int w;  // вага ребра (натуральне число)
};

// ---------- DSU (система неперетинних множин) ----------
// Структура для швидкої перевірки, чи належать дві вершини
// одній компоненті зв'язності, та їх об'єднання.
// Використовується в алгоритмі Краскала, щоб визначити,
// чи додавання ребра утворює цикл.
struct DSU {
    vector<int> parent;  // parent[x] — батько елемента x у дереві DSU
    vector<int> rnk;     // ранг (оцінка висоти) для об'єднання за рангом

    // Конструктор: спочатку кожна вершина — корінь своєї множини.
    // Вершини нумеруються від 1 до n, тому розмір n+1.
    DSU(int n) : parent(n + 1), rnk(n + 1, 0) {
        for (int i = 0; i <= n; i++) parent[i] = i;
    }

    // Пошук представника (кореня) множини, до якої належить x.
    // Стиснення шляху: під час пошуку кожен відвіданий вузол
    // одразу прив'язується до кореня, щоб наступні виклики були
    // майже миттєвими.
    int find(int x) {
        while (parent[x] != x) {
            parent[x] = parent[parent[x]];  // стиснення шляху
            x = parent[x];
        }
        return x;
    }

    // Об'єднання множин, до яких належать a і b.
    // Повертає true, якщо вони були різними (ребро додано до кістяка),
    // та false, якщо вже в одній множині (ребро утворює цикл).
    // Об'єднання за рангом: корінь з меншим рангом підпорядковується
    // кореню з більшим, щоб дерево залишалось неглибоким.
    bool unite(int a, int b) {
        a = find(a);
        b = find(b);
        if (a == b) return false;          // вже в одній компоненті — цикл
        if (rnk[a] < rnk[b]) swap(a, b);  // об'єднання за рангом
        parent[b] = a;
        if (rnk[a] == rnk[b]) rnk[a]++;   // збільшити ранг при рівності
        return true;
    }
};

// ============================================================
// Функція генерації випадкового зв'язкового графа.
//
// Призначення: створити файл input.txt з випадковим неорієнтованим
// зваженим зв'язковим графом, щоб можна було тестувати алгоритм
// Краскала без ручного введення даних.
//
// Параметри:
//   n — кількість вершин (має бути >= 1)
//   m — кількість ребер (має бути >= n-1, щоб граф був зв'язковим)
//
// Алгоритм генерації:
//   1. Спочатку будуємо випадкове кістякове дерево з n-1 ребер,
//      що гарантує зв'язність графа.
//   2. Додаємо випадкові ребра, поки їх кількість не досягне m.
//      Дублікати та петлі (ребра з однаковими кінцями) відкидаються.
//   3. Кожному ребру призначається випадкова вага від 1 до 30000.
//   4. Результат записується у файл input.txt у форматі:
//        N M
//        A1 B1 C1
//        ...
// ============================================================
void generateRandomGraph(int n, int m) {
    // Перевірка коректності параметрів.
    if (n < 1) n = 1;
    if (m < n - 1) m = n - 1;  // мінімум для зв'язності

    // Максимальна кількість різних ребер у простому графі: n*(n-1)/2.
    int maxEdges = (n > 1) ? n * (n - 1) / 2 : 0;
    if (m > maxEdges) m = maxEdges;

    mt19937 gen(12345);  // фіксований seed для відтворюваності результатів
    uniform_int_distribution<int> wdist(1, 30000);  // ваги від 1 до 30000

    set<pair<int,int>> used;  // множина вже використаних ребер (без дублікатів)
    vector<Edge> edges;
    edges.reserve(m);

    // Крок 1: випадкове кістякове дерево (гарантує зв'язність).
    // З'єднуємо вершини 2..n з випадковою попередньою вершиною з 1..i-1.
    for (int i = 2; i <= n; i++) {
        uniform_int_distribution<int> vdist(1, i - 1);
        int u = vdist(gen);
        int a = min(u, i), b = max(u, i);
        used.insert({a, b});
        edges.push_back({u, i, wdist(gen)});
    }

    // Крок 2: додаємо випадкові ребра до досягнення m.
    uniform_int_distribution<int> vdist(1, n);
    while ((int)edges.size() < m && (int)used.size() < maxEdges) {
        int u = vdist(gen);
        int v = vdist(gen);
        if (u == v) continue;  // без петель
        int a = min(u, v), b = max(u, v);
        if (used.count({a, b})) continue;  // без дублікатів
        used.insert({a, b});
        edges.push_back({u, v, wdist(gen)});
    }

    // Крок 3: запис у файл input.txt.
    ofstream out("input.txt");
    if (!out) {
        cerr << "Не вдалося створити input.txt\n";
        return;
    }
    out << n << " " << edges.size() << "\n";
    for (const auto& e : edges) {
        out << e.u << " " << e.v << " " << e.w << "\n";
    }
    out.close();
}

// ============================================================
// Головна функція програми.
//
// Використання:
//   ./main.exe                  — розв'язати задачу (читає input.txt)
//   ./main.exe N M              — згенерувати випадковий граф з N
//                                 вершин і M ребер у файл input.txt
// ============================================================
int main(int argc, char* argv[]) {
    // Якщо передано два аргументи — режим генерації випадкового графа.
    if (argc >= 3) {
        int n = atoi(argv[1]);
        int m = atoi(argv[2]);
        generateRandomGraph(n, m);
        cout << "Згенеровано input.txt: N=" << n << ", M=" << m << "\n";
        return 0;
    }

    // --- Крок 1: читання вхідних даних з файлу input.txt ---
    // Якщо файлу input.txt немає у поточній директорії — створюємо його
    // автоматично з випадковим зв'язковим графом (N=8, M=15), щоб програма
    // могла працювати "з коробки" без ручного введення даних.
    ifstream in("input.txt");
    if (!in) {
        cout << "Файл input.txt не знайдено. Генеруємо випадковий граф...\n";
        generateRandomGraph(8, 15);
        in.open("input.txt");
        if (!in) {
            cerr << "Не вдалося створити input.txt\n";
            return 1;
        }
    }

    int n, m;  // n — кількість вершин, m — кількість ребер
    if (!(in >> n >> m)) {  // читаємо N і M
        cerr << "Помилка читання N, M\n";
        return 1;
    }

    vector<Edge> edges;      // масив усіх ребер графа
    edges.reserve(m);        // резервуємо пам'ять для m ребер
    for (int i = 0; i < m; i++) {
        Edge e;
        // читаємо трійку: номери вершин A, B та вагу C
        if (!(in >> e.u >> e.v >> e.w)) {
            cerr << "Помилка читання ребра " << i + 1 << "\n";
            return 1;
        }
        edges.push_back(e);
    }
    in.close();  // закриваємо вхідний файл

    // --- Крок 2: сортування ребер за вагою (зростання) ---
    // Краскал вимагає розглядати ребра від найлегшого до найважчого.
    sort(edges.begin(), edges.end(), [](const Edge& a, const Edge& b) {
        return a.w < b.w;  // порівняння за вагою
    });

    // --- Крок 3: ініціалізація DSU ---
    // Кожна вершина спочатку у власній компоненті.
    DSU dsu(n);

    // --- Крок 4: побудова мінімального кістяка ---
    long long total = 0;  // сумарна вага мінімального кістяка
    int used = 0;         // кількість доданих ребер (має стати n-1)

    // Перебираємо ребра від найлегшого до найважчого.
    for (const auto& e : edges) {
        // Якщо кінці ребра у різних компонентах — додаємо його.
        if (dsu.unite(e.u, e.v)) {
            total += e.w;           // додаємо вагу до відповіді
            if (++used == n - 1)    // кістяк має рівно n-1 ребро
                break;              // всі вершини з'єднано — завершуємо
        }
        // інакше ребро пропускається (утворює цикл)
    }

    // --- Крок 5: запис результату у файл output.txt ---
    ofstream out("output.txt");
    if (!out) {
        cerr << "Не вдалося створити output.txt\n";
        return 1;
    }
    out << total << "\n";  // єдине число — вага мінімального кістяка
    out.close();

    // Повідомлення користувачу в консоль (для зручності).
    cout << "Вага мінімального кістяка: " << total << "\n";
    return 0;
}
